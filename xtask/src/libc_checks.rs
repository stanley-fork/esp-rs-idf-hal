//! `cargo xtask libc-checks`

use std::collections::{BTreeMap, BTreeSet};
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::{env, fs};

use anyhow::{bail, Context, Result};
use clap::Args;
use syn::visit::Visit;

const ITEMS: &str = "esp-idf-sys/build/libc_items.rs";
const LIBC_GIT: &str = "https://github.com/rust-lang/libc";

/// The primitive (or C) types a constant has to resolve to, to be checked by value
const INT_TYPES: &[&str] = &[
    "i8",
    "i16",
    "i32",
    "i64",
    "i128",
    "isize",
    "u8",
    "u16",
    "u32",
    "u64",
    "u128",
    "usize",
    "c_char",
    "c_schar",
    "c_uchar",
    "c_short",
    "c_ushort",
    "c_int",
    "c_uint",
    "c_long",
    "c_ulong",
    "c_longlong",
    "c_ulonglong",
];

const HEADER: &str = "\
// @generated by `cargo xtask libc-checks`, do not edit.
// The `libc` items which every supported `libc` version and configuration has, for
// `libc_checks.rs` to check against the ESP-IDF bindings.
";

#[derive(Args)]
pub struct LibcChecks {
    /// Fail if `libc_items.rs` is not up to date, rather than updating it
    #[arg(long)]
    check: bool,

    /// A target to expand `libc` for; the Xtensa ones need the `esp` toolchain (`cargo +esp xtask`)
    #[arg(
        long = "target",
        value_name = "TRIPLE",
        default_values = ["riscv32imc-esp-espidf"]
    )]
    targets: Vec<String>,

    /// A `libc` to take the items from: `min` (the workspace's minimum version), `latest` (the
    /// newest 0.2 release), `workspace` (the one in `Cargo.lock`), `git[:<branch>]`
    /// (rust-lang/libc, `libc-0.2` by default), a version, or a path
    #[arg(long = "libc", value_name = "SPEC", default_values = ["min", "latest"])]
    libcs: Vec<String>,

    /// A space-separated list of `--cfg`s to expand each `libc` with
    #[arg(
        long = "cfgs",
        value_name = "CFGS",
        default_values = ["espidf_time64", "espidf_time64 espidf_picolibc", "espidf_time32"]
    )]
    cfgs: Vec<String>,
}

/// The public structs, other types and integer constants of an expanded `libc`
#[derive(Default)]
struct Items {
    /// Struct name -> its public named fields, in declaration order
    structs: BTreeMap<String, Vec<String>>,
    /// Type aliases, unions and tuple structs
    types: BTreeSet<String>,
    /// Constant name -> its type
    consts: BTreeMap<String, syn::Type>,
    /// Type alias name -> the aliased type
    aliases: BTreeMap<String, syn::Type>,
}

impl Items {
    fn parse(source: &str) -> Result<Self> {
        let mut items = Self::default();
        items.visit_file(&syn::parse_file(source)?);
        Ok(items)
    }

    /// The names of the types, structs included
    fn all_types(&self) -> BTreeSet<&str> {
        self.structs
            .keys()
            .chain(&self.types)
            .map(String::as_str)
            .collect()
    }

    /// The names of the constants whose type resolves to an integer
    fn int_consts(&self) -> BTreeSet<&str> {
        self.consts
            .iter()
            .filter(|(_, ty)| self.is_int(ty, 0))
            .map(|(name, _)| name.as_str())
            .collect()
    }

    fn is_int(&self, ty: &syn::Type, depth: usize) -> bool {
        let syn::Type::Path(path) = ty else {
            return false;
        };

        let Some(last) = path.path.segments.last() else {
            return false;
        };

        if path.qself.is_some() || !last.arguments.is_none() {
            return false;
        }

        let name = last.ident.to_string();

        INT_TYPES.contains(&name.as_str())
            || depth < 8
                && self
                    .aliases
                    .get(&name)
                    .is_some_and(|ty| self.is_int(ty, depth + 1))
    }
}

impl<'ast> Visit<'ast> for Items {
    fn visit_item_struct(&mut self, item: &'ast syn::ItemStruct) {
        if !is_pub(&item.vis) {
            return;
        }

        if let syn::Fields::Named(fields) = &item.fields {
            let fields = fields
                .named
                .iter()
                .filter(|field| is_pub(&field.vis))
                .filter_map(|field| field.ident.as_ref().map(ToString::to_string))
                .collect();
            self.structs.entry(item.ident.to_string()).or_insert(fields);
        } else {
            self.types.insert(item.ident.to_string());
        }
    }

    fn visit_item_union(&mut self, item: &'ast syn::ItemUnion) {
        if is_pub(&item.vis) {
            self.types.insert(item.ident.to_string());
        }
    }

    fn visit_item_type(&mut self, item: &'ast syn::ItemType) {
        if is_pub(&item.vis) {
            self.types.insert(item.ident.to_string());
        }

        self.aliases
            .insert(item.ident.to_string(), (*item.ty).clone());
    }

    fn visit_item_const(&mut self, item: &'ast syn::ItemConst) {
        if is_pub(&item.vis) {
            self.consts
                .insert(item.ident.to_string(), (*item.ty).clone());
        }
    }
}

pub fn run(args: LibcChecks) -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .context("No workspace root")?;

    let mut libc_items = Vec::new();

    for spec in &args.libcs {
        let dir = libc_dir(root, spec)?;

        for target in &args.targets {
            for cfgs in &args.cfgs {
                eprintln!(
                    "Expanding libc `{spec}` ({}) for `{target}` with `{cfgs}`",
                    dir.display()
                );

                let expanded = expand(root, &dir, target, cfgs)?;
                libc_items
                    .push(Items::parse(&expanded).context("Failed to parse the expanded libc")?);
            }
        }
    }

    let generated = rustfmt(&inventory(&libc_items))?;

    let path = root.join(ITEMS);
    let current = fs::read_to_string(&path).unwrap_or_default();

    if current == generated {
        eprintln!("`{ITEMS}` is up to date");
    } else if args.check {
        bail!("`{ITEMS}` is not up to date, run `cargo xtask libc-checks`");
    } else {
        fs::write(&path, generated)?;
        eprintln!("Updated `{ITEMS}`");
    }

    Ok(())
}

/// The source of `libc_items.rs`: the items which every expanded `libc` has
fn inventory(libcs: &[Items]) -> String {
    let in_all = |names: fn(&Items) -> BTreeSet<&str>| {
        let mut sets = libcs.iter().map(names);
        let first = sets.next().unwrap_or_default();

        sets.fold(first, |all, set| all.intersection(&set).copied().collect())
    };

    let structs = in_all(|items| items.structs.keys().map(String::as_str).collect());
    let types = in_all(Items::all_types);
    let consts = in_all(Items::int_consts);

    let mut out = HEADER.to_string();

    out.push_str("\npub const STRUCTS: &[(&str, &[&str])] = &[\n");

    for name in &structs {
        let fields: Vec<_> = libcs[0].structs[*name]
            .iter()
            .filter(|field| {
                libcs
                    .iter()
                    .all(|items| items.structs[*name].contains(field))
            })
            .map(|field| format!("{field:?}"))
            .collect();

        out.push_str(&format!("({name:?}, &[{}]),\n", fields.join(", ")));
    }

    out.push_str("];\n\npub const TYPES: &[&str] = &[\n");

    for name in types.difference(&structs) {
        out.push_str(&format!("{name:?},\n"));
    }

    out.push_str("];\n\npub const CONSTS: &[&str] = &[\n");

    for name in &consts {
        out.push_str(&format!("{name:?},\n"));
    }

    out.push_str("];\n");

    out
}

fn is_pub(vis: &syn::Visibility) -> bool {
    matches!(vis, syn::Visibility::Public(_))
}

/// The package directory of the `libc` selected by `spec`
fn libc_dir(root: &Path, spec: &str) -> Result<PathBuf> {
    let requirement = match spec {
        "workspace" => return package_dir(root),
        "min" => format!("\"={}\"", min_libc(root)?),
        "latest" => "\"0.2\"".to_string(),
        _ if spec == "git" || spec.starts_with("git:") => {
            let branch = spec.strip_prefix("git:").unwrap_or("libc-0.2");
            format!("{{ git = \"{LIBC_GIT}\", branch = \"{branch}\" }}")
        }
        _ if Path::new(spec).is_dir() => return Ok(PathBuf::from(spec)),
        _ => format!("\"={spec}\""),
    };

    let probe = scratch_dir(&format!("libc-{spec}"))?;

    fs::write(
        probe.join("Cargo.toml"),
        format!(
            "[package]\nname = \"libc-probe\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n\
             [lib]\npath = \"lib.rs\"\n\n[dependencies]\nlibc = {requirement}\n\n[workspace]\n"
        ),
    )?;
    fs::write(probe.join("lib.rs"), "")?;

    // Resolve afresh, or `latest` and `git` would stay at what they were in the previous run
    let _ = fs::remove_file(probe.join("Cargo.lock"));

    package_dir(&probe)
}

/// The package directory of the `libc` which the workspace in `dir` resolves to
fn package_dir(dir: &Path) -> Result<PathBuf> {
    let metadata = cargo_metadata::MetadataCommand::new()
        .current_dir(dir)
        .exec()?;

    let libc = metadata
        .packages
        .iter()
        .find(|package| package.name == "libc")
        .with_context(|| format!("No `libc` in the workspace of {}", dir.display()))?;

    Ok(libc
        .manifest_path
        .parent()
        .context("No `libc` package directory")?
        .as_std_path()
        .to_path_buf())
}

/// The minimum `libc` version of the workspace
fn min_libc(root: &Path) -> Result<String> {
    let manifest: toml::Table = fs::read_to_string(root.join("Cargo.toml"))?.parse()?;

    let libc = manifest
        .get("workspace")
        .and_then(|workspace| workspace.get("dependencies"))
        .and_then(|dependencies| dependencies.get("libc"))
        .context("No `libc` in the workspace dependencies")?;

    let version = libc
        .as_str()
        .or_else(|| libc.get("version").and_then(toml::Value::as_str))
        .context("No `libc` version in the workspace dependencies")?;

    Ok(version.trim_start_matches(['^', '=', '~']).to_string())
}

/// The macro-expanded source of the `libc` in `dir`, as `rustc` sees it for `target` and `cfgs`
fn expand(root: &Path, dir: &Path, target: &str, cfgs: &str) -> Result<String> {
    // A fresh copy with a manifest of our own: cargo writes nothing next to the `libc` sources,
    // and does not skip the build as fresh
    let copy = scratch_dir("expand")?;
    let _ = fs::remove_dir_all(copy.join("src"));

    copy_dir(&dir.join("src"), &copy.join("src"))?;
    fs::copy(dir.join("build.rs"), copy.join("build.rs"))?;
    fs::write(
        copy.join("Cargo.toml"),
        "[package]\nname = \"libc\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n\
         [lints.rust]\nunexpected_cfgs = \"allow\"\n\n[workspace]\n",
    )?;

    let output = Command::new(env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .current_dir(&copy)
        .env("RUSTC_BOOTSTRAP", "1")
        .env_remove("RUSTFLAGS")
        .env_remove("CARGO_ENCODED_RUSTFLAGS")
        .args(["rustc", "--lib", "--profile", "check", "-Zbuild-std=core"])
        .args(["--target", target, "--target-dir"])
        .arg(root.join("target").join("xtask"))
        .args(["--", "-Zunpretty=expanded"])
        .args(cfgs.split_whitespace().flat_map(|cfg| ["--cfg", cfg]))
        .output()?;

    if !output.status.success() {
        bail!(
            "Expanding libc in {} failed:\n{}",
            dir.display(),
            String::from_utf8_lossy(&output.stderr)
        );
    }

    Ok(String::from_utf8(output.stdout)?)
}

/// `source` formatted with `rustfmt`
fn rustfmt(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2021"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .context("Failed to run rustfmt")?;

    child
        .stdin
        .take()
        .context("No rustfmt stdin")?
        .write_all(source.as_bytes())?;

    let output = child.wait_with_output()?;

    if !output.status.success() {
        bail!("rustfmt failed");
    }

    Ok(String::from_utf8(output.stdout)?)
}

/// A directory of this task under the system temp directory, created if missing
fn scratch_dir(name: &str) -> Result<PathBuf> {
    let name: String = name
        .chars()
        .map(|c| {
            if c.is_alphanumeric() || c == '-' || c == '.' {
                c
            } else {
                '_'
            }
        })
        .collect();
    let dir = env::temp_dir().join("esp-idf-xtask").join(name);

    fs::create_dir_all(&dir)?;

    Ok(dir)
}

fn copy_dir(from: &Path, to: &Path) -> Result<()> {
    fs::create_dir_all(to)?;

    for entry in fs::read_dir(from)? {
        let entry = entry?;
        let path = entry.path();

        if entry.file_type()?.is_dir() {
            copy_dir(&path, &to.join(entry.file_name()))?;
        } else {
            fs::copy(&path, to.join(entry.file_name()))?;
        }
    }

    Ok(())
}
